export const CATALOGS = { vi, en } as const;
export type TranslationKey = keyof typeof vi;

export const normalizeLocale = (value?: string | null): AppLocale => value === 'en' ? 'en' : 'vi';

export const translate = (
  locale: AppLocale,
  key: TranslationKey,
  variables: TranslationVariables = {},
): string => Object.entries(variables).reduce(
  (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
  CATALOGS[locale][key],
);

export const intlLocale = (locale: AppLocale): string => locale === 'en' ? 'en-US' : 'vi-VN';
