export const translate = (
  locale: AppLocale,
  key: TranslationKey,
  variables: TranslationVariables = {},
): string => Object.entries(variables).reduce(
  (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
  CATALOGS[locale][key],
);

